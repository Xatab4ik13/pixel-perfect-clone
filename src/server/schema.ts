// Drizzle schema for the Лазейка product backend (our own Postgres).
// This is intentionally separate from drizzle/schema.ts (Lovable/Supabase-managed).
// Migrations are hand-written SQL under drizzle/migrations/* to keep full control
// (see 0001_core_product.sql). This file provides typing for drizzle-orm queries.
import { sql } from "drizzle-orm";
import {
  pgTable,
  uuid,
  text,
  bigint,
  integer,
  boolean,
  timestamp,
  jsonb,
  index,
} from "drizzle-orm/pg-core";

/**
 * A product user. Because this is a Telegram Mini App, identity is 1:1 with a
 * Telegram account, so the Telegram identity lives directly on the user row.
 */
export const users = pgTable(
  "users",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    // Telegram numeric user id (fits in i64; Postgres bigint).
    telegramUserId: bigint("telegram_user_id", { mode: "number" }).notNull().unique(),
    username: text("username"),
    firstName: text("first_name"),
    lastName: text("last_name"),
    photoUrl: text("photo_url"),
    languageCode: text("language_code"),
    isPremium: boolean("is_premium").notNull().default(false),
    // Access-control role. 'user' is a regular customer; the rest are staff.
    role: text("role").notNull().default("user"), // user | viewer | operator | admin
    // Shareable referral code (lowercase hex), generated by the DB default.
    referralCode: text("referral_code")
      .notNull()
      .default(sql`substr(replace(gen_random_uuid()::text, '-', ''), 1, 8)`),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => ({
    roleIdx: index("users_role_idx").on(t.role),
    referralCodeIdx: index("users_referral_code_idx").on(t.referralCode),
  }),
);

/**
 * Referral attribution + reward lifecycle. One row per invited user. The
 * referrer earns free days when the invited friend makes their first payment.
 */
export const referrals = pgTable(
  "referrals",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    referrerUserId: uuid("referrer_user_id").notNull().references(() => users.id, { onDelete: "cascade" }),
    referredUserId: uuid("referred_user_id").notNull().unique().references(() => users.id, { onDelete: "cascade" }),
    status: text("status").notNull().default("pending"), // pending | rewarded
    rewardDays: integer("reward_days").notNull().default(0),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    rewardedAt: timestamp("rewarded_at", { withTimezone: true }),
  },
  (t) => ({
    referrerIdx: index("referrals_referrer_idx").on(t.referrerUserId),
    statusIdx: index("referrals_status_idx").on(t.status),
  }),
);

/**
 * One access subscription per user. Renewals extend currentPeriodEnd.
 * telemtUsername links the row to the per-user secret provisioned on the telemt
 * node via its control-plane API. The ee-link (contains the user's secret) is
 * stored here because the DB is our secret store — it must NEVER be logged or
 * committed, only returned to its owner.
 */
export const subscriptions = pgTable(
  "subscriptions",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id").notNull().unique().references(() => users.id, { onDelete: "cascade" }),
    status: text("status").notNull().default("pending"), // pending | active | expired | canceled
    planId: text("plan_id"), // month | quarter | year (last purchased plan)
    currentPeriodEnd: timestamp("current_period_end", { withTimezone: true }),
    // telemt control-plane linkage
    telemtUsername: text("telemt_username").unique(),
    maxUniqueIps: integer("max_unique_ips"),
    // The issued tg://proxy link (secret-bearing). Owner-only.
    link: text("link"),
    secretFingerprint: text("secret_fingerprint"),
    // Mask (SNI) domain baked into this user's link; null = default PROXY_SNI.
    sniDomain: text("sni_domain"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => ({
    statusIdx: index("subscriptions_status_idx").on(t.status),
    periodEndIdx: index("subscriptions_period_end_idx").on(t.currentPeriodEnd),
  }),
);

/**
 * Payment attempts. Idempotent on providerPaymentId so webhook retries are safe.
 * Amounts are stored in minor units (kopecks) to avoid float issues.
 */
export const payments = pgTable(
  "payments",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id").notNull().references(() => users.id, { onDelete: "cascade" }),
    planId: text("plan_id").notNull(),
    amountKopecks: integer("amount_kopecks").notNull(),
    currency: text("currency").notNull().default("RUB"),
    provider: text("provider").notNull().default("sbp"),
    providerPaymentId: text("provider_payment_id").unique(),
    status: text("status").notNull().default("pending"), // pending | paid | failed | refunded | canceled
    daysGranted: integer("days_granted").notNull(),
    // Raw provider payload for audit/debugging. Must not contain card data.
    raw: jsonb("raw"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    paidAt: timestamp("paid_at", { withTimezone: true }),
  },
  (t) => ({
    userIdx: index("payments_user_idx").on(t.userId),
    statusIdx: index("payments_status_idx").on(t.status),
  }),
);

/**
 * Append-only audit trail for staff actions (suspend, rotate, refund, role
 * changes). Never store secrets here.
 */
export const auditEvents = pgTable(
  "audit_events",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    actorUserId: uuid("actor_user_id").references(() => users.id, { onDelete: "set null" }),
    action: text("action").notNull(),
    targetUserId: uuid("target_user_id").references(() => users.id, { onDelete: "set null" }),
    reason: text("reason"),
    meta: jsonb("meta"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => ({
    actorIdx: index("audit_events_actor_idx").on(t.actorUserId),
    createdIdx: index("audit_events_created_idx").on(t.createdAt),
  }),
);

/**
 * Staff accounts for the admin panel. Separate from product `users` (which are
 * Telegram-authenticated). Admins log in with email + password.
 */
export const adminUsers = pgTable(
  "admin_users",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    email: text("email").notNull().unique(),
    passwordHash: text("password_hash").notNull(),
    role: text("role").notNull().default("admin"), // viewer | operator | admin
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    lastLoginAt: timestamp("last_login_at", { withTimezone: true }),
  },
);

export type AdminUser = typeof adminUsers.$inferSelect;
export type User = typeof users.$inferSelect;
export type NewUser = typeof users.$inferInsert;
export type Subscription = typeof subscriptions.$inferSelect;
export type Payment = typeof payments.$inferSelect;
export type AuditEvent = typeof auditEvents.$inferSelect;
export type Referral = typeof referrals.$inferSelect;
